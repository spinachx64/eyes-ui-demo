#!/usr/bin/env python3
"""Generate Arduino and ESP-IDF C++ presets from presets.json."""
from pathlib import Path
import json
import math

ROOT = Path(__file__).resolve().parent.parent
FIELDS = ('x', 'y', 'w', 'h', 'angle', 'lid', 'tilt', 'curve')


def generate(settings):
    emotions = settings['emotions']
    if not emotions:
        raise ValueError('At least one emotion is required')
    ids = set()
    rows = []
    for emotion in emotions:
        identifier = emotion['id']
        if not isinstance(identifier, str) or not identifier or '\0' in identifier or identifier in ids:
            raise ValueError(f'Emotion id must be a unique nonempty string: {identifier!r}')
        ids.add(identifier)
        label = emotion['name']
        if not isinstance(label, str) or '\0' in label:
            raise ValueError(f'{identifier}: name must be a string without NUL')
        poses = []
        for side in ('left', 'right'):
            pose = emotion[side]
            values = [float(pose[field]) for field in FIELDS]
            if not all(math.isfinite(v) and abs(v) <= 10000 for v in values):
                raise ValueError(f'{identifier}/{side}: pose values must be finite and within +/-10000')
            if pose['w'] <= 0 or pose['h'] <= 0 or not 0 <= pose['lid'] <= 1:
                raise ValueError(f'{identifier}/{side}: w/h must be positive and lid must be in [0,1]')
            poses.append('{' + ', '.join(f'{v:.3f}f' for v in values) + '}')
        strings = [json.dumps(s, ensure_ascii=False) for s in (identifier, label)]
        rows.append(f'  {{{strings[0]}, {strings[1]}, {poses[0]}, {poses[1]} }},\n')
    return '''// AUTO-GENERATED by tools/generate_presets.py. Do not edit directly.
#pragma once
struct EyePose { float x, y, w, h, angle, lid, tilt, curve; };
struct EmotionPreset { const char* id; const char* label; EyePose left; EyePose right; };
static constexpr EmotionPreset kPresets[] = {
''' + ''.join(rows) + '''};
static constexpr int kPresetCount = sizeof(kPresets) / sizeof(kPresets[0]);
'''


def main():
    header = generate(json.loads((ROOT / 'presets.json').read_text(encoding='utf-8')))
    for relative in ('firmware/eyes_demo/presets.h', 'components/eyes/src/presets.h'):
        (ROOT / relative).write_text(header, encoding='utf-8')
        print(f'Generated {relative}')


if __name__ == '__main__':
    main()
